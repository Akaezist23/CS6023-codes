#!/usr/bin/env python3
# Writes src/scene_adversarial.h: a 5,000-sphere scene meant to be hard for the BVH.
# Usage: python3 make_adversarial_scene.py   (deterministic, seed 6023)
#
# Layout: sparse, tiny spheres (r 0.01-0.03) spread through a large volume in front of the
# camera (z in [-40, -1], x within the view, y in [-0.5, 6]). Rays pass close to many spheres
# but rarely hit one, so the traversal finds no early hit and cannot skip far boxes.
# This was the hardest of several layouts measured on the CPU (box + sphere tests per
# camera ray, scene.h = 33 + 5): tunnel 29 + 3, mixed big/small overlapping 56-70 + 5-8,
# sparse tiny spheres 103 + 10. Overlapping boxes cost less than expected because big
# spheres get hit early; missing everything is what makes the BVH work hard.
# Output format is the same as scene.h; scene[0] is the same floor.
import random

N = 5000
random.seed(6023)

spheres = []
for i in range(N):
    r = random.uniform(0.01, 0.03)
    z = random.uniform(-40.0, -1.0)
    half = 0.9 * (3.0 - z)                   # keep x roughly inside the view cone (camera at z = 3)
    x = random.uniform(-half, half)
    y = random.uniform(-0.5 + 0.5 * r, 6.0)
    col = tuple(random.uniform(0.1, 0.95) for _ in range(3))
    k = random.choice((0.0, 0.3, 0.5, 0.7, 0.9))
    spheres.append((x, y, z, r, col, k))

with open("src/scene_adversarial.h", "w") as f:
    f.write("// Adversarial scene for the BVH (generated by make_adversarial_scene.py, seed 6023).\n")
    f.write("// Include AFTER Vec3 and Sphere are defined. scene[0] is the same floor as scene.h;\n")
    f.write(f"// {N} sparse tiny spheres follow (r 0.01-0.03, z in [-40, -1], x within the view, y in [-0.5, 6]).\n")
    f.write("// Select it with -DSCENE_FILE='\"scene_adversarial.h\"' (scripts: SCENE=scene_adversarial.h).\n")
    f.write("#pragma once\n\nstd::vector<Sphere> scene = {\n")
    f.write("    { Vec3(0, -1000.5f, -1), 1000.0f, Vec3(0.5f, 0.5f, 0.5f), 0.2f, true  }, // floor\n")
    for x, y, z, r, c, k in spheres:
        f.write(f"    {{ Vec3({x:8.3f}f, {y:7.3f}f, {z:8.3f}f), {r:.3f}f, "
                f"Vec3({c[0]:.2f}f, {c[1]:.2f}f, {c[2]:.2f}f), {k:.1f}f, false }},\n")
    f.write("};\n")
print(f"Wrote src/scene_adversarial.h ({N} spheres + floor)")
